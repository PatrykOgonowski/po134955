public class Uzytkownik {

    String imie;
    int id;
    int max_kalorie;
    int max_wegle;
    int max_tluszcze;
    int max_bialko;

    public Uzytkownik(int id, String imie, int max_kalorie, int max_wegle, int max_tluszcze, int max_bialko){
        this.id = id;
        this.imie = imie;
        this.max_kalorie = max_kalorie;
        this.max_wegle = max_wegle;
        this.max_tluszcze = max_tluszcze;
        this.max_bialko = max_bialko;

    }

}
